CREATE TABLE IF NOT EXISTS locataire(
  id integer generated by default as identity primary key,
  denomination denomination NOT NULL DEFAULT 'Mr',
  prenom TEXT NOT NULL,
  nom TEXT NOT NULL,
  email TEXT NULL,
  fk_actif int REFERENCES actif ON DELETE NO ACTION ON UPDATE CASCADE,
  periode_occupation daterange NOT NULL,
  loyer_mensuel_hc numeric NOT NULL,
  montant_caution NUMERIC NOT NULL,
  provision_charge_mensuelle numeric NOT NULL,
  loyer_total numeric GENERATED ALWAYS AS( loyer_mensuel_hc + provision_charge_mensuelle ) STORED,
  date_depart_reelle date NULL DEFAULT NULL, -- antérieure à la date de début du bail / impacte les chambres disponibles
  date_cloturabilite_effective date NULL DEFAULT NULL,
  est_entree_directe boolean not null default true,
  est_charge_cloturable boolean not null default false,
  est_charge_cloture boolean not null default false, -- si ON a une date de fin de bail
  note text NULL,
  EXCLUDE USING gist (
    fk_actif WITH =,
    periode_occupation WITH &&
  )
);




CREATE TABLE IF NOT EXISTS charges(
  id integer generated by default as identity primary key,
  fk_type_charge smallserial not null references type_charge on update cascade on delete no action,
  fk_locataire integer references locataire( id ) on update cascade on delete no action, --> si not null, charge non fractionnable, individuelle
  fk_bien integer REFERENCES bien ON UPDATE CASCADE ON DELETE NO ACTION,
  date_emission timestamp with time zone not null,
  periode daterange,
  montant numeric not null,
  nb_jours smallint GENERATED ALWAYS AS ( upper( periode ) - lower( periode ) ) STORED,
  montant_journalier real GENERATED ALWAYS AS ( montant / ( upper( periode ) - lower( periode ) ) ) STORED,
  reference_facture TEXT NULL,
  contenu pdf NULL,
  file_name text NULL,
  note TEXT NULL,
  CONSTRAINT periode_not_null CHECK ( ( fk_type_charge = 9999 AND periode IS NULL ) OR ( fk_type_charge <> 9999 AND periode IS NOT NULL )),
  EXCLUDE USING  gist(
    fk_type_charge with =,
    periode with &&
  )
);




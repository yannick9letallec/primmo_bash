CREATE TABLE IF NOT EXISTS compte (
	id integer generated by default as identity primary key,
	label text NOT NULL,
	ts_created_at timestamp NOT NULL DEFAULT now(),
	fk_created_by SMALLINT REFERENCES compte ON DELETE NO ACTION ON UPDATE CASCADE,
	config hstore NULL, -- quotas /// quota_disk / quota_user
